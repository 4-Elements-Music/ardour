/**
 * Create a safe Lua variable name from an arbitrary string.
 */
function safeName(name) {
  return name.replace(/[^a-zA-Z0-9]/g, '_').toLowerCase();
}

/**
 * Convert a 1-based bar number to ticks, respecting time signatures.
 * Simplified: uses the first time signature for the whole piece.
 */
function barToTicks(bar, timeSigs) {
  const ts = (timeSigs && timeSigs[0]) || { numerator: 4, denominator: 4 };
  const bpb = ts.numerator * (4 / ts.denominator);
  return ((bar - 1) * bpb) * 1920;
}

/**
 * Convert 1-based bar and beat to ticks.
 */
function barBeatToTicks(bar, beat, timeSigs) {
  return barToTicks(bar, timeSigs) + ((beat - 1) * 1920);
}

/**
 * Get beats per bar for a given bar number.
 */
function beatsPerBar(_bar, timeSigs) {
  const ts = (timeSigs && timeSigs[0]) || { numerator: 4, denominator: 4 };
  return ts.numerator * (4 / ts.denominator);
}

/**
 * Convert a duration in bars to ticks.
 */
function durationToTicks(bars, timeSigs) {
  return barToTicks(bars + 1, timeSigs);
}
