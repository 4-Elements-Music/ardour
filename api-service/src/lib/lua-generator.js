import { resolve } from 'path';
import { luaString, resolveLibraryPath } from './sanitizer.js';

/**
 * Generate a Lua script from a JSON job spec that drives Ardour's headless engine.
 *
 * @param {object} spec - The validated job spec
 * @param {string} jobDir - Absolute path to this job's working directory
 * @param {string} libraryBaseDir - Absolute path to the audio library root
 * @returns {string} Lua script content
 */
export function generateLuaScript(spec, jobDir, libraryBaseDir) {
  const lines = [];
  const exportDir = resolve(jobDir, 'export');
  const sessionDir = resolve(jobDir, 'session');
  const sessionName = 'job-session';
  const sampleRate = spec.session.sample_rate;

  lines.push('-- Auto-generated by ardour-headless-api');
  lines.push('-- DO NOT EDIT');
  lines.push('');

  // ── 1. Audio backend setup ──
  lines.push('AudioEngine:set_backend("None (Dummy)", "", "")');
  lines.push(`AudioEngine:set_sample_rate(${sampleRate})`);
  lines.push('AudioEngine:set_buffer_size(1024)');
  lines.push('AudioEngine:start()');
  lines.push('');
  lines.push(`create_session(${luaString(sessionDir)}, ${luaString(sessionName)}, ${sampleRate})`);
  lines.push('');

  // ── 2. Tempo map ──
  lines.push('local tm = Temporal.TempoMap.write_copy()');
  for (let i = 0; i < spec.session.tempo.length; i++) {
    const t = spec.session.tempo[i];
    const pos = barToTicks(t.bar, spec.session.time_signature);
    if (t.ramp && i > 0) {
      const prev = spec.session.tempo[i - 1];
      lines.push(`tm:set_tempo(Temporal.Tempo(${prev.bpm}, ${t.bpm}, 4), Temporal.timepos_t.from_ticks(${pos}))`);
    } else {
      lines.push(`tm:set_tempo(Temporal.Tempo(${t.bpm}, ${t.bpm}, 4), Temporal.timepos_t.from_ticks(${pos}))`);
    }
  }
  for (const ts of spec.session.time_signature) {
    const pos = barToTicks(ts.bar, spec.session.time_signature);
    lines.push(`tm:set_meter(Temporal.Meter(${ts.numerator}, ${ts.denominator}), Temporal.timepos_t.from_ticks(${pos}))`);
  }
  lines.push('Temporal.TempoMap.update(tm)');
  lines.push('');

  // ── 3. Buses (create before tracks so sends can reference them) ──
  if (spec.buses) {
    for (const bus of spec.buses) {
      const busVar = `bus_${safeName(bus.name)}`;
      lines.push(`-- Bus: ${bus.name}`);
      lines.push(`local ${busVar} = Session:new_audio_route(2, 2, ARDOUR.RouteGroup(), 1, ${luaString(bus.name)}, ARDOUR.PresentationInfo.Flag.AudioBus, ARDOUR.PresentationInfo.max_order):front()`);
      emitMixerSettings(lines, busVar, bus);
      emitPlugins(lines, busVar, bus.plugins || []);
      lines.push('');
    }
  }

  // ── 4. Tracks ──
  for (const track of spec.tracks) {
    const varName = `track_${safeName(track.name)}`;
    lines.push(`-- Track: ${track.name}`);

    if (track.type === 'audio') {
      const ch = track.channels || 2;
      lines.push(`local ${varName} = Session:new_audio_track(${ch}, ${ch}, ARDOUR.RouteGroup(), 1, ${luaString(track.name)}, ARDOUR.PresentationInfo.max_order, ARDOUR.TrackMode.Normal, true):front()`);
    } else if (track.type === 'midi') {
      lines.push(`local ${varName}_list = Session:new_midi_track(ARDOUR.ChanCount(ARDOUR.DataType("midi"), 1), ARDOUR.ChanCount(ARDOUR.DataType("audio"), 2), true, ARDOUR.PluginInfo(), nil, ARDOUR.RouteGroup(), 1, ${luaString(track.name)}, ARDOUR.PresentationInfo.max_order, ARDOUR.TrackMode.Normal, true, false)`);
      lines.push(`local ${varName} = ${varName}_list:front()`);
    }

    // Instrument (for MIDI tracks, added at position 0)
    if (track.type === 'midi' && track.instrument) {
      emitInstrument(lines, varName, track.instrument, libraryBaseDir);
    }

    // Regions
    for (const region of (track.regions || [])) {
      emitRegion(lines, varName, track, region, spec, libraryBaseDir);
    }

    // Plugins
    emitPlugins(lines, varName, track.plugins || []);

    // Mixer settings
    emitMixerSettings(lines, varName, track);

    // Automation
    if (track.automation) {
      emitAutomation(lines, varName, track.automation);
    }

    // Sends
    if (track.sends) {
      emitSends(lines, varName, track.sends);
    }

    lines.push('');
  }

  // ── 4b. Group bus routing (deferred — tracks must exist first) ──
  if (spec.buses) {
    for (const bus of spec.buses) {
      if (bus.type === 'group' && bus.source_tracks) {
        const busVar = `bus_${safeName(bus.name)}`;
        lines.push(`-- Route sources to group bus: ${bus.name}`);
        for (const srcName of bus.source_tracks) {
          lines.push(`do local src = Session:route_by_name(${luaString(srcName)})`);
          lines.push(`if src and not src:isnil() then Session:add_internal_send(src, nil, ${busVar}) end end`);
        }
        lines.push('');
      }
    }
  }

  // ── 5. Master bus ──
  if (spec.master) {
    lines.push('-- Master bus');
    lines.push('local master = Session:master_out()');
    emitMixerSettings(lines, 'master', spec.master);
    emitPlugins(lines, 'master', spec.master.plugins || []);
    lines.push('');
  }

  // ── 5b. VCAs ──
  if (spec.vcas) {
    for (const vca of spec.vcas) {
      lines.push(`-- VCA: ${vca.name}`);
      lines.push(`Session:vca_manager():create_vca(1, ${luaString(vca.name)})`);
      lines.push('do');
      lines.push(`  local vca = Session:vca_manager():vca_by_name(${luaString(vca.name)})`);
      lines.push('  if vca and not vca:isnil() then');
      for (const controlName of vca.controls) {
        lines.push(`    do local r = Session:route_by_name(${luaString(controlName)})`);
        lines.push('    if r and not r:isnil() then r:to_slavable():assign(vca) end end');
      }
      if (vca.gain_db !== undefined) {
        const coeff = Math.pow(10, vca.gain_db / 20);
        lines.push(`    vca:gain_control():set_value(${coeff}, PBD.GroupControlDisposition.NoGroup)`);
      }
      lines.push('  end');
      lines.push('end');
      lines.push('');
    }
  }

  // ── 5c. Markers ──
  if (spec.markers) {
    lines.push('-- Markers');
    lines.push('do');
    lines.push('  local locs = Session:locations()');
    for (const marker of spec.markers) {
      const ticks = barToTicks(marker.bar, spec.session.time_signature);
      lines.push(`  local loc = locs:add_range(Temporal.timepos_t.from_ticks(${ticks}), Temporal.timepos_t.from_ticks(${ticks}))`);
      lines.push(`  if loc then loc:set_name(${luaString(marker.name)}) end`);
    }
    lines.push('end');
    lines.push('');
  }

  // ── 5d. Track groups ──
  const groupNames = new Set();
  for (const track of spec.tracks) {
    if (track.group) groupNames.add(track.group);
  }
  if (groupNames.size > 0) {
    lines.push('-- Track groups');
    for (const groupName of groupNames) {
      const groupVar = `grp_${safeName(groupName)}`;
      lines.push(`local ${groupVar} = Session:new_route_group(${luaString(groupName)})`);
      for (const track of spec.tracks) {
        if (track.group === groupName) {
          lines.push(`do local r = Session:route_by_name(${luaString(track.name)}); if r and not r:isnil() then ${groupVar}:add(r) end end`);
        }
      }
      lines.push('');
    }
  }

  // ── 6. Session range ──
  const totalTicks = durationToTicks(spec.session.duration_bars, spec.session.time_signature);
  lines.push(`Session:maybe_update_session_range(Temporal.timepos_t(0), Temporal.timepos_t.from_ticks(${totalTicks}))`);
  lines.push('');

  // ── 7. Save and export ──
  lines.push('Session:save_state("")');
  lines.push('');
  lines.push(`os.execute("mkdir -p " .. ${luaString(exportDir)})`);

  // Calculate export range
  let exportRangeStart, exportRangeEnd;
  if (spec.session.render_range) {
    const startTicks = barToTicks(spec.session.render_range.start_bar, spec.session.time_signature);
    const endTicks = barToTicks(spec.session.render_range.end_bar, spec.session.time_signature);
    exportRangeStart = `Temporal.timepos_t.from_ticks(${startTicks}):samples()`;
    exportRangeEnd = `Temporal.timepos_t.from_ticks(${endTicks}):samples()`;
  } else {
    exportRangeStart = 'Session:current_start_sample()';
    exportRangeEnd = 'Session:current_end_sample()';
  }

  const formats = spec.output.formats || [{ format: 'wav', bit_depth: 24, sample_rate: sampleRate }];
  for (const fmt of formats) {
    const bitDepth = fmt.bit_depth || 24;
    const fmtSampleRate = fmt.sample_rate || sampleRate;
    lines.push('do');
    lines.push('  local se = Session:simple_export()');
    lines.push('  se:set_name("output")');
    lines.push(`  se:set_folder(${luaString(exportDir)})`);
    lines.push(`  se:set_range(${exportRangeStart}, ${exportRangeEnd})`);
    // CD preset for 16-bit 44100, WAV@session for everything else
    if (bitDepth === 16 && fmtSampleRate === 44100) {
      lines.push('  se:set_preset("df340c53-88b5-4342-a1c8-58e0704872ea")');
    } else {
      lines.push('  se:set_preset("75969a1c-3133-4694-864b-a1fa50e43348")');
    }
    lines.push('  se:check_outputs()');
    lines.push('  se:run_export()');
    lines.push('end');
    lines.push('');
  }

  // ── 7b. Stem export ──
  if (spec.output.stems) {
    const stemTracks = spec.output.stem_groups && spec.output.stem_groups.length > 0
      ? spec.output.stem_groups
      : spec.tracks.map(t => t.name);

    lines.push('-- Stem exports');
    for (const trackName of stemTracks) {
      lines.push('do');
      lines.push(`  local stem_route = Session:route_by_name(${luaString(trackName)})`);
      lines.push('  if stem_route and not stem_route:isnil() then');
      lines.push('    stem_route:solo_control():set_value(1, PBD.GroupControlDisposition.NoGroup)');
      for (const fmt of formats) {
        const bitDepth = fmt.bit_depth || 24;
        const fmtSampleRate = fmt.sample_rate || sampleRate;
        lines.push('    do');
        lines.push('      local se = Session:simple_export()');
        lines.push(`      se:set_name(${luaString('stem_' + trackName)})`);
        lines.push(`      se:set_folder(${luaString(exportDir)})`);
        lines.push(`      se:set_range(${exportRangeStart}, ${exportRangeEnd})`);
        if (bitDepth === 16 && fmtSampleRate === 44100) {
          lines.push('      se:set_preset("df340c53-88b5-4342-a1c8-58e0704872ea")');
        } else {
          lines.push('      se:set_preset("75969a1c-3133-4694-864b-a1fa50e43348")');
        }
        lines.push('      se:check_outputs()');
        lines.push('      se:run_export()');
        lines.push('    end');
      }
      lines.push('    stem_route:solo_control():set_value(0, PBD.GroupControlDisposition.NoGroup)');
      lines.push('  end');
      lines.push('end');
    }
    lines.push('');
  }

  // ── 8. Close session ──
  lines.push('close_session()');

  return lines.join('\n');
}

// ────────────────────────────────────────────────────────
// Region emission
// ────────────────────────────────────────────────────────

function emitRegion(lines, trackVar, track, region, spec, libraryBaseDir) {
  const pos = barBeatToTicks(region.position_bar || 1, region.position_beat || 1, spec.session.time_signature);

  if (region.file) {
    // Audio file region
    const filePath = resolveLibraryPath(region.file, libraryBaseDir);
    lines.push('do');
    lines.push(`  local rgn = ARDOUR.LuaAPI.import_audio_file(Session, ${luaString(filePath)})`);
    lines.push('  if not rgn:isnil() then');

    // Start offset
    if (region.start_offset_ms && region.start_offset_ms > 0) {
      const offsetSamples = Math.round((region.start_offset_ms / 1000) * spec.session.sample_rate);
      lines.push(`    rgn:set_start(Temporal.timepos_t(${offsetSamples}))`);
    }

    // Trim to length
    if (region.length_bars) {
      const lenTicks = region.length_bars * beatsPerBar(region.position_bar || 1, spec.session.time_signature) * 1920;
      lines.push(`    rgn:set_length(Temporal.timecnt_t.from_ticks(${lenTicks}))`);
    }

    // Time-stretch / pitch-shift (audio only, uses Rubberband)
    if ((region.time_stretch_ratio && region.time_stretch_ratio !== 1.0) ||
        (region.pitch_shift_semitones && region.pitch_shift_semitones !== 0)) {
      const stretch = region.time_stretch_ratio || 1.0;
      const pitchExpr = region.pitch_shift_semitones
        ? `2 ^ (${region.pitch_shift_semitones} / 12.0)`
        : '1.0';
      lines.push('    local ar = rgn:to_audioregion()');
      lines.push('    if ar and not ar:isnil() then');
      lines.push('      local rb = ARDOUR.LuaAPI.Rubberband(ar, false)');
      lines.push(`      rb:set_strech_and_pitch(${stretch}, ${pitchExpr})`);
      lines.push('      local stretched = rb:process(function(p) return false end)');
      lines.push('      if stretched and not stretched:isnil() then rgn = stretched end');
      lines.push('    end');
    }

    // Per-region gain
    if (region.gain_db && region.gain_db !== 0) {
      lines.push('    do local ar = rgn:to_audioregion()');
      lines.push(`    if ar and not ar:isnil() then ar:set_scale_amplitude(10 ^ (${region.gain_db} / 20)) end end`);
    }

    // Fades
    if (region.fade_in_ms) {
      const samples = Math.round((region.fade_in_ms / 1000) * spec.session.sample_rate);
      lines.push('    do local ar = rgn:to_audioregion()');
      lines.push(`    if ar and not ar:isnil() then ar:set_fade_in_length(${samples}) end end`);
    }
    if (region.fade_out_ms) {
      const samples = Math.round((region.fade_out_ms / 1000) * spec.session.sample_rate);
      lines.push('    do local ar = rgn:to_audioregion()');
      lines.push(`    if ar and not ar:isnil() then ar:set_fade_out_length(${samples}) end end`);
    }

    // Place region on playlist (with optional loop copies)
    const loopCount = region.loop_count || 1;
    lines.push(`    local pl = ${trackVar}:to_track():playlist()`);
    if (loopCount > 1) {
      lines.push('    local rgn_len = rgn:length():samples()');
      lines.push(`    for i = 0, ${loopCount - 1} do`);
      lines.push(`      local copy = (i == 0) and rgn or ARDOUR.RegionFactory.clone_region(rgn, true, false)`);
      lines.push(`      pl:add_region(copy, Temporal.timepos_t.from_ticks(${pos} + i * rgn_len), 1, false, 0, 0, false)`);
      lines.push('    end');
    } else {
      lines.push(`    pl:add_region(rgn, Temporal.timepos_t.from_ticks(${pos}), 1, false, 0, 0, false)`);
    }

    lines.push('  end');
    lines.push('end');

  } else if (region.notes) {
    // Inline MIDI region
    const bpb = beatsPerBar(region.position_bar || 1, spec.session.time_signature);
    const lenTicks = (region.length_bars || 4) * bpb * 1920;
    lines.push('do');
    lines.push(`  local midi_track = ${trackVar}:to_track():to_midi_track()`);
    lines.push(`  local mr = ARDOUR.LuaAPI.create_midi_region(midi_track, Temporal.timepos_t.from_ticks(${pos}), Temporal.timecnt_t.from_ticks(${lenTicks}), ${luaString(track.name + ' region')})`);
    lines.push('  if not mr:isnil() then');
    lines.push('    local src = mr:midi_source(0)');
    lines.push('    local model = src:model()');
    lines.push('    local cmd = model:new_note_diff_command("Add notes")');

    for (const note of region.notes) {
      const ch = note.channel || 0;
      lines.push(`    cmd:add(ARDOUR.LuaAPI.new_noteptr(${ch}, Temporal.Beats(${note.start_beat}, 0), Temporal.Beats(${note.duration_beats}, 0), ${note.pitch}, ${note.velocity}))`);
    }

    lines.push('    model:apply_diff_command_as_commit(Session, cmd)');

    // MIDI CC automation
    if (region.cc && region.cc.length > 0) {
      const byController = new Map();
      for (const cc of region.cc) {
        if (!byController.has(cc.controller)) byController.set(cc.controller, []);
        byController.get(cc.controller).push(cc);
      }
      for (const [controller, events] of byController) {
        lines.push(`    do local param = Evoral.Parameter(ARDOUR.AutomationType.MidiCCAutomation, 0, ${controller})`);
        lines.push(`    local ac = ${trackVar}:automation_control(param, true)`);
        lines.push('    if ac and not ac:isnil() then');
        lines.push('      local al = ac:alist()');
        for (const cc of events) {
          const beatTicks = cc.time_beat * 1920;
          lines.push(`      al:add(Temporal.timepos_t.from_ticks(${pos} + ${beatTicks}), ${cc.value / 127.0}, false, true)`);
        }
        lines.push('      ac:set_automation_state(ARDOUR.AutoState.Play)');
        lines.push('    end end');
      }
    }

    // MIDI pitch bend automation
    if (region.pitch_bend && region.pitch_bend.length > 0) {
      lines.push(`    do local param = Evoral.Parameter(ARDOUR.AutomationType.MidiPitchBenderAutomation, 0, 0)`);
      lines.push(`    local ac = ${trackVar}:automation_control(param, true)`);
      lines.push('    if ac and not ac:isnil() then');
      lines.push('      local al = ac:alist()');
      for (const pb of region.pitch_bend) {
        const beatTicks = pb.time_beat * 1920;
        lines.push(`      al:add(Temporal.timepos_t.from_ticks(${pos} + ${beatTicks}), ${pb.value / 16383.0}, false, true)`);
      }
      lines.push('      ac:set_automation_state(ARDOUR.AutoState.Play)');
      lines.push('    end end');
    }

    // Loop copies for MIDI
    const loopCount = region.loop_count || 1;
    if (loopCount > 1) {
      lines.push('    local pl = midi_track:playlist()');
      lines.push(`    for i = 1, ${loopCount - 1} do`);
      lines.push('      local copy = ARDOUR.RegionFactory.clone_region(mr, true, false)');
      lines.push(`      pl:add_region(copy, Temporal.timepos_t.from_ticks(${pos} + i * ${lenTicks}), 1, false, 0, 0, false)`);
      lines.push('    end');
    }

    lines.push('  end');
    lines.push('end');
  }
}

// ────────────────────────────────────────────────────────
// Plugin emission
// ────────────────────────────────────────────────────────

function emitPlugins(lines, routeVar, plugins) {
  for (let i = 0; i < plugins.length; i++) {
    const plugin = plugins[i];
    const plugVar = `plugin_${i}`;
    lines.push('do');
    lines.push(`  local ${plugVar} = ARDOUR.LuaAPI.new_plugin(Session, ${luaString(plugin.uri)}, ARDOUR.PluginType.LV2, ${luaString(plugin.preset || '')})`);
    lines.push(`  if not ${plugVar}:isnil() then`);
    lines.push(`    ${routeVar}:add_processor_by_index(${plugVar}, ${i}, nil, true)`);

    if (plugin.params) {
      lines.push(`    local pi = ${plugVar}:to_insert()`);
      for (const [paramIdx, value] of Object.entries(plugin.params)) {
        lines.push(`    ARDOUR.LuaAPI.set_processor_param(pi, ${paramIdx}, ${value})`);
      }
    }

    if (plugin.sidechain_source) {
      lines.push(`    local pi = ${plugVar}:to_insert()`);
      lines.push('    if pi and not pi:isnil() then');
      lines.push('      pi:add_sidechain()');
      lines.push(`      local src = Session:route_by_name(${luaString(plugin.sidechain_source)})`);
      lines.push('      if src and not src:isnil() then');
      lines.push('        local sc_in = pi:sidechain_input()');
      lines.push('        if sc_in and not sc_in:isnil() then');
      lines.push('          sc_in:connect(src:output():audio(0):name(), sc_in:audio(0):name(), nil)');
      lines.push('        end');
      lines.push('      end');
      lines.push('    end');
    }

    lines.push('  end');
    lines.push('end');
  }
}

// ────────────────────────────────────────────────────────
// Instrument emission (MIDI track, position 0)
// ────────────────────────────────────────────────────────

function emitInstrument(lines, trackVar, instrument, libraryBaseDir) {
  lines.push('do');
  lines.push(`  local inst = ARDOUR.LuaAPI.new_plugin(Session, ${luaString(instrument.uri)}, ARDOUR.PluginType.LV2, ${luaString(instrument.preset || '')})`);
  lines.push('  if not inst:isnil() then');
  lines.push(`    ${trackVar}:add_processor_by_index(inst, 0, nil, true)`);

  if (instrument.files) {
    lines.push('    local pi = inst:to_insert()');
    for (const file of instrument.files) {
      const filePath = resolveLibraryPath(file, libraryBaseDir);
      lines.push(`    ARDOUR.LuaAPI.set_plugin_insert_property(pi, ${luaString(instrument.file_property_uri || 'http://www.fluidsynth.org/sf2')}, ${luaString(filePath)})`);
    }
  }

  if (instrument.bank !== undefined || instrument.program !== undefined) {
    lines.push('    local pi2 = inst:to_insert()');
    if (instrument.bank !== undefined) {
      lines.push(`    ARDOUR.LuaAPI.set_processor_param(pi2, 2, ${instrument.bank})`);
    }
    if (instrument.program !== undefined) {
      lines.push(`    ARDOUR.LuaAPI.set_processor_param(pi2, 3, ${instrument.program})`);
    }
  }

  lines.push('  end');
  lines.push('end');
}

// ────────────────────────────────────────────────────────
// Mixer settings
// ────────────────────────────────────────────────────────

function emitMixerSettings(lines, routeVar, settings) {
  if (settings.gain_db !== undefined) {
    const coeff = Math.pow(10, settings.gain_db / 20);
    lines.push(`${routeVar}:gain_control():set_value(${coeff}, PBD.GroupControlDisposition.NoGroup)`);
  }
  if (settings.pan !== undefined) {
    lines.push(`do local pc = ${routeVar}:pan_azimuth_control(); if pc and not pc:isnil() then pc:set_value(${settings.pan}, PBD.GroupControlDisposition.NoGroup) end end`);
  }
  if (settings.mute) {
    lines.push(`${routeVar}:mute_control():set_value(1, PBD.GroupControlDisposition.NoGroup)`);
  }
  if (settings.solo) {
    lines.push(`${routeVar}:solo_control():set_value(1, PBD.GroupControlDisposition.NoGroup)`);
  }
  if (settings.phase_invert) {
    lines.push(`${routeVar}:phase_control():set_value(1, PBD.GroupControlDisposition.NoGroup)`);
  }
}

// ────────────────────────────────────────────────────────
// Automation curves
// ────────────────────────────────────────────────────────

function emitAutomation(lines, routeVar, automations) {
  for (const auto of automations) {
    if (auto.target === 'gain') {
      lines.push('do');
      lines.push(`  local ac = ${routeVar}:gain_control()`);
      lines.push('  local al = ac:alist()');
      lines.push('  al:clear_list()');
      for (const pt of auto.points) {
        const ticks = barBeatToTicks(pt.bar || 1, pt.beat || 1, [{ bar: 1, numerator: 4, denominator: 4 }]);
        const val = pt.value_db !== undefined ? Math.pow(10, pt.value_db / 20) : pt.value;
        lines.push(`  al:add(Temporal.timepos_t.from_ticks(${ticks}), ${val}, false, true)`);
      }
      lines.push('  ac:set_automation_state(ARDOUR.AutoState.Play)');
      lines.push('end');

    } else if (auto.target === 'pan') {
      lines.push('do');
      lines.push(`  local ac = ${routeVar}:pan_azimuth_control()`);
      lines.push('  if ac and not ac:isnil() then');
      lines.push('    local al = ac:alist()');
      lines.push('    al:clear_list()');
      for (const pt of auto.points) {
        const ticks = barBeatToTicks(pt.bar || 1, pt.beat || 1, [{ bar: 1, numerator: 4, denominator: 4 }]);
        lines.push(`    al:add(Temporal.timepos_t.from_ticks(${ticks}), ${pt.value}, false, true)`);
      }
      lines.push('    ac:set_automation_state(ARDOUR.AutoState.Play)');
      lines.push('  end');
      lines.push('end');

    } else if (auto.target === 'mute') {
      lines.push('do');
      lines.push(`  local ac = ${routeVar}:mute_control()`);
      lines.push('  local al = ac:alist()');
      lines.push('  al:clear_list()');
      for (const pt of auto.points) {
        const ticks = barBeatToTicks(pt.bar || 1, pt.beat || 1, [{ bar: 1, numerator: 4, denominator: 4 }]);
        const val = pt.value !== undefined ? pt.value : 0;
        lines.push(`  al:add(Temporal.timepos_t.from_ticks(${ticks}), ${val}, false, true)`);
      }
      lines.push('  ac:set_automation_state(ARDOUR.AutoState.Play)');
      lines.push('end');

    } else if (auto.target === 'plugin') {
      lines.push('do');
      lines.push(`  local proc = ${routeVar}:nth_plugin(${auto.plugin_index || 0})`);
      lines.push('  if proc and not proc:isnil() then');
      lines.push(`    local al, cl, pd = ARDOUR.LuaAPI.plugin_automation(proc, ${auto.param_index || 0})`);
      lines.push('    if al and not al:isnil() then');
      lines.push('      cl:clear_list()');
      for (const pt of auto.points) {
        const ticks = barBeatToTicks(pt.bar || 1, pt.beat || 1, [{ bar: 1, numerator: 4, denominator: 4 }]);
        lines.push(`      cl:add(Temporal.timepos_t.from_ticks(${ticks}), ${pt.value}, false, true)`);
      }
      lines.push('    end');
      lines.push('  end');
      lines.push('end');
    }
  }
}

